package io.github.borey.recorderautotranscribe;

import android.app.Application;
import android.app.job.JobService;
import android.app.job.JobParameters;
import android.content.Context;
import android.os.Bundle;
import java.util.ArrayList;
import java.lang.reflect.Method;
import de.robv.android.xposed.XC_MethodHook;
import de.robv.android.xposed.IXposedHookLoadPackage;
import de.robv.android.xposed.XposedBridge;
import de.robv.android.xposed.XposedHelpers;
import de.robv.android.xposed.callbacks.XC_LoadPackage.LoadPackageParam;

public final class MainHook implements IXposedHookLoadPackage {
    static final String TARGET = "com.coloros.soundrecorder";
    static final String SCAN_NOW_ACTION = "io.github.borey.recorderautotranscribe.SCAN_NOW";
    static final String AUTO_SERVICE = "com.soundrecorder.convertservice.autogeneratedtext.AutoGeneratedTextJobService";
    static final int PERIODIC_JOB_ID = 0x43545232;
    static final int NATIVE_JOB_ID = 0x2711;

    private static final Object INSTALL_LOCK = new Object();
    private static final ArrayList<ScheduledJobStart> pendingJobStarts = new ArrayList<>();
    private static boolean recorderAttachHookInstalled;
    private static boolean recorderInstallAttempted;
    private static volatile RecorderBridge bridge;

    private static final class ScheduledJobStart {
        final JobService service;
        final JobParameters parameters;
        ScheduledJobStart(JobService service, JobParameters parameters) {
            this.service = service;
            this.parameters = parameters;
        }
    }

    @Override public void handleLoadPackage(LoadPackageParam p) {
        if (SummaryServiceHook.PACKAGE.equals(p.packageName)) {
            SummaryServiceHook.install(p.classLoader);
            return;
        }
        if (!TARGET.equals(p.packageName) || !TARGET.equals(p.processName)) return;
        synchronized (INSTALL_LOCK) {
            if (recorderAttachHookInstalled) return;
            recorderAttachHookInstalled = true;
        }
        try {
            XposedHelpers.findAndHookMethod(Application.class, "attach", Context.class, new XC_MethodHook() {
                @Override protected void afterHookedMethod(MethodHookParam param) {
                    Object attached = param.args != null && param.args.length > 0 ? param.args[0] : null;
                    if (attached instanceof Context) installRecorderHooks((Context) attached, p.classLoader);
                    else logCompatibility("application attach did not provide a context; hooks not installed", null);
                }
            });
        } catch (Throwable error) {
            logCompatibility("unable to register application attach hook", error);
        }
    }

    /**
     * The package version is available only after Application.attach. Keep the only early hook on
     * a framework class, then validate every private recorder symbol before installing any hook on
     * the recorder itself.
     */
    private static void installRecorderHooks(Context context, ClassLoader loader) {
        if (context == null || !TARGET.equals(context.getPackageName())) return;
        synchronized (INSTALL_LOCK) {
            if (recorderInstallAttempted) return;
            recorderInstallAttempted = true;
        }

        final String version;
        try {
            version = context.getPackageManager().getPackageInfo(TARGET, 0).versionName;
        } catch (Throwable error) {
            logCompatibility("could not read recorder version; hooks not installed", error);
            publishCompatibility(context, "无法读取录音机版本，模块未加载");
            return;
        }
        if (!ModulePolicy.supports(version)) {
            logCompatibility("unsupported recorder version " + version + "; hooks not installed", null);
            publishCompatibility(context, "录音机版本 " + version + " 暂不兼容，模块未加载");
            return;
        }

        final Class<?> service;
        final Class<?> summaryKit;
        final Class<?> summaryEntity;
        final Class<?> summaryEvents;
        final Class<?> status;
        try {
            service = requireClass(AUTO_SERVICE, loader);
            summaryKit = requireClass("com.soundrecorder.summary.kit.w", loader);
            summaryEntity = requireClass("com.soundrecorder.summary.request.database.SummaryCacheEntity", loader);
            summaryEvents = requireClass("vg.l", loader);
            status = requireClass("com.soundrecorder.convertservice.convert.asr.FileAsrStatusController", loader);

            requireMethod(service, "onStartJob", JobParameters.class);
            requireMethod(service, "onStopJob", JobParameters.class);
            requireMethod(summaryKit, "m", Long.class, summaryEntity, java.util.List.class);
            requireMethod(summaryEvents, "onDataEvent", String.class, String.class, Bundle.class);
            requireMethod(summaryEvents, "onSummaryKitError", String.class, int.class, String.class);
            requireMethod(summaryEvents, "onUserEvent", String.class, String.class, Bundle.class);
            requireMethod(status, "onConvertStatusChange", int.class, boolean.class);
        } catch (Throwable error) {
            logCompatibility("recorder 16.17.8 is missing a required capability; hooks not installed", error);
            publishCompatibility(context, "录音机缺少所需接口，模块未加载");
            return;
        }

        try {
            XposedHelpers.findAndHookMethod(summaryKit, "m", Long.class, summaryEntity, java.util.List.class,
                    new XC_MethodHook() {
                        @Override protected void afterHookedMethod(MethodHookParam param) {
                            if (bridge != null && param.args[1] != null && param.getThrowable() == null) {
                                bridge.summarySaved(param.args[1]);
                            }
                        }
                    });
            XposedHelpers.findAndHookMethod(summaryEvents, "onDataEvent", String.class, String.class, Bundle.class,
                    new XC_MethodHook() {
                        @Override protected void afterHookedMethod(MethodHookParam param) {
                            if (bridge != null) bridge.summaryEvent((String) param.args[1], (Bundle) param.args[2]);
                        }
                    });
            XposedHelpers.findAndHookMethod(summaryEvents, "onSummaryKitError", String.class, int.class, String.class,
                    new XC_MethodHook() {
                        @Override protected void afterHookedMethod(MethodHookParam param) {
                            if (bridge != null) bridge.summaryError((Integer) param.args[1]);
                        }
                    });
            XposedHelpers.findAndHookMethod(summaryEvents, "onUserEvent", String.class, String.class, Bundle.class,
                    new XC_MethodHook() {
                        @Override protected void afterHookedMethod(MethodHookParam param) {
                            if (bridge != null) bridge.summaryEvent((String) param.args[1], (Bundle) param.args[2]);
                        }
                    });
            XposedHelpers.findAndHookMethod(status, "onConvertStatusChange", int.class, boolean.class,
                    new XC_MethodHook() {
                        @Override protected void afterHookedMethod(MethodHookParam param) {
                            if (bridge != null) bridge.recordStatus(param.thisObject, (Integer) param.args[0]);
                        }
                    });
            XposedHelpers.findAndHookMethod(service, "onStartJob", JobParameters.class, new XC_MethodHook() {
                @Override protected void beforeHookedMethod(MethodHookParam param) {
                    if (param.args == null || param.args.length == 0
                            || !(param.args[0] instanceof JobParameters)) return;
                    int id = ((JobParameters) param.args[0]).getJobId();
                    if ((id != PERIODIC_JOB_ID && id != NATIVE_JOB_ID) || !(param.thisObject instanceof JobService)) return;
                    JobService service = (JobService) param.thisObject;
                    JobParameters parameters = (JobParameters) param.args[0];
                    try {
                        enqueueScheduledJob(service, parameters);
                        // The queue scan runs asynchronously. Keep JobScheduler's wakelock until
                        // its scan receipt calls jobFinished(), including the cold-start path.
                        param.setResult(true);
                    } catch (Throwable error) {
                        logCompatibility("could not track periodic job callback", error);
                    }
                }
            });
            XposedHelpers.findAndHookMethod(service, "onStopJob", JobParameters.class, new XC_MethodHook() {
                @Override protected void beforeHookedMethod(MethodHookParam param) {
                    if (param.args == null || param.args.length == 0
                            || !(param.args[0] instanceof JobParameters)) return;
                    JobParameters parameters = (JobParameters) param.args[0];
                    int id = parameters.getJobId();
                    if (id != PERIODIC_JOB_ID && id != NATIVE_JOB_ID) return;
                    try {
                        // Retry only when this token has no saved scan receipt.
                        param.setResult(stopScheduledJob(parameters));
                    } catch (Throwable error) {
                        logCompatibility("could not track periodic job interruption", error);
                        param.setResult(true);
                    }
                }
            });

            try { RecorderSettingsEntry.install(loader); }
            catch (Throwable error) { logCompatibility("recorder settings entry unavailable", error); }
            try { RecorderHomeEntry.install(); }
            catch (Throwable error) { logCompatibility("recorder home entry unavailable", error); }

            Context appContext = context.getApplicationContext();
            if (appContext == null) appContext = context;
            final Context bridgeContext = appContext;
            RecorderBridge current;
            ArrayList<ScheduledJobStart> pending;
            synchronized (INSTALL_LOCK) {
                if (bridge == null) bridge = new RecorderBridge(bridgeContext, loader);
                current = bridge;
                pending = new ArrayList<>(pendingJobStarts);
                pendingJobStarts.clear();
            }
            for (ScheduledJobStart job : pending) current.onScheduledJob(job.service, job.parameters);
            current.start();
            logCompatibility("recorder 16.17.8 hooks active", null);
        } catch (Throwable error) {
            logCompatibility("recorder hook installation failed", error);
            publishCompatibility(context, "录音机模块加载失败，请查看 LSPosed 日志");
        }
    }

    private static void enqueueScheduledJob(JobService service, JobParameters parameters) {
        RecorderBridge current;
        synchronized (INSTALL_LOCK) {
            current = bridge;
            if (current == null) {
                for (ScheduledJobStart pending : pendingJobStarts) {
                    if (pending.parameters == parameters) return;
                }
                pendingJobStarts.add(new ScheduledJobStart(service, parameters));
                return;
            }
        }
        current.onScheduledJob(service, parameters);
    }

    private static boolean stopScheduledJob(JobParameters parameters) {
        RecorderBridge current;
        synchronized (INSTALL_LOCK) {
            current = bridge;
            if (current == null) {
                for (int i = pendingJobStarts.size() - 1; i >= 0; i--) {
                    if (pendingJobStarts.get(i).parameters == parameters) pendingJobStarts.remove(i);
                }
                return true;
            }
        }
        return current.onScheduledJobStopped(parameters);
    }

    private static Class<?> requireClass(String name, ClassLoader loader) throws ClassNotFoundException {
        return Class.forName(name, false, loader);
    }

    private static void requireMethod(Class<?> type, String name, Class<?>... parameterTypes)
            throws NoSuchMethodException {
        Method method = type.getDeclaredMethod(name, parameterTypes);
        if (method == null) throw new NoSuchMethodException(type.getName() + "#" + name);
    }

    private static void logCompatibility(String state, Throwable error) {
        XposedBridge.log("RecorderAutoTranscribe: " + state);
        if (error != null) XposedBridge.log(error);
    }

    /** Reports compatibility failures through the recorder-UID-checked module bridge. */
    private static void publishCompatibility(Context context, String message) {
        try { ModuleBridgeReceiver.reportError(context, message); }
        catch (Throwable error) { logCompatibility("unable to publish compatibility status", error); }
    }
}
