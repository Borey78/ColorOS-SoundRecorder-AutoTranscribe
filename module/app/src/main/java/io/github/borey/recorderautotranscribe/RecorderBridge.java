    private Object onMainScheduledScan(Callable<Object> action) throws Exception {
        FutureTask<Object> task = new FutureTask<>(() -> {
            // The worker-side check is not enough: JobScheduler can stop us while this task is
            // waiting in the main queue. Serialize the final cancellation check with onStopJob.
            synchronized (scanLock) {
                throwIfStoppedJobScan();
                return action.call();
            }
        });
        main.post(task);
        try {
            return task.get(8, TimeUnit.SECONDS);
        } catch (ExecutionException e) {
            Throwable cause=e.getCause();
            if(cause instanceof Exception)throw (Exception)cause;
            if(cause instanceof Error)throw (Error)cause;
            throw e;
        }
    }
