    void start() {
        try {
            String version = context.getPackageManager().getPackageInfo(MainHook.TARGET, 0).versionName;
            supported = ModulePolicy.supports(version);
        } catch (Throwable e) {
            supported = false;
            report(e);
        }
        try {
            context.registerReceiver(new BroadcastReceiver() {
                @Override public void onReceive(Context c, Intent i) {
                    // The first bridge read may have failed before the token was loaded.
                    // Android supplies the sender package only when it opted in to sharing
                    // identity; this lets the module UI wake a stuck queue safely.
                    boolean moduleSender=Build.VERSION.SDK_INT>=34
                            && ModuleSettings.PACKAGE.equals(getSentFromPackage());
                    if (moduleSender || accepts(i.getStringExtra("token"))) refresh();
                }
            }, new IntentFilter(MainHook.SCAN_NOW_ACTION), Context.RECEIVER_EXPORTED);
        } catch (Throwable e) {
            report(e);
        }
        registerPeriodicJob();

        long now = System.currentTimeMillis();
        lifecycle.onBridgeReady(now);
        persistLifecycleState();
        boolean waitingForJob = scheduledJobs.onBridgeReady();
        bridgeReady = true;
        worker.post(() -> publishHealth("桥接器已就绪；后台周期任务状态已核对"));
        XposedBridge.log("RecorderAutoTranscribe: bridge ready");
        if (waitingForJob) requestScheduledScan();
        else refresh();
    }

    private void registerPeriodicJob() {
        final long interval = 15 * 60 * 1000L;
        ComponentName component = new ComponentName(MainHook.TARGET, MainHook.AUTO_SERVICE);
        try {
            JobScheduler jobs = context.getSystemService(JobScheduler.class);
            jobs.cancel(0x43545231);
            jobs.cancel(MainHook.NATIVE_JOB_ID);
            JobInfo existing = jobs.getPendingJob(MainHook.PERIODIC_JOB_ID);
            if (existing != null && existing.isPeriodic() && existing.getIntervalMillis() == interval
                    && component.equals(existing.getService())) {
                periodicScheduled = true;
                scheduleStatus = "后台周期检查已登记（空闲时约 15 分钟检查）";
                lifecycle.onScheduleVerified(System.currentTimeMillis());
                persistLifecycleState();
                XposedBridge.log("RecorderAutoTranscribe: existing 15-minute job verified");
                return;
            }
            int result = jobs.schedule(new JobInfo.Builder(MainHook.PERIODIC_JOB_ID, component)
                    .setPeriodic(interval).build());
            periodicScheduled = result == JobScheduler.RESULT_SUCCESS;
            if (periodicScheduled) {
                lifecycle.onScheduleVerified(System.currentTimeMillis());
                persistLifecycleState();
            }
            scheduleStatus = periodicScheduled
                    ? "后台周期检查已登记（空闲时约 15 分钟检查）"
                    : "后台周期检查登记失败；将使用低频本地兜底";
            XposedBridge.log("RecorderAutoTranscribe: periodic job registration "
                    + (periodicScheduled ? "succeeded" : "failed"));
        } catch (Throwable e) {
            periodicScheduled = false;
            scheduleStatus = "后台周期检查登记失败；将使用低频本地兜底";
            report(e);
        }
    }

    void onScheduledJob(JobService service, JobParameters parameters) {
        if (service == null || parameters == null) return;
        synchronized (scanLock) {
            boolean added = scheduledJobs.onJobStart(parameters);
            if (!added) return;
            synchronized (activeJobServices) { activeJobServices.put(parameters, service); }
            lifecycle.onJobStarted(System.currentTimeMillis());
        }
        persistLifecycleState();
        XposedBridge.log("RecorderAutoTranscribe: system job started id=" + parameters.getJobId());
        if (bridgeReady) requestScheduledScan();
    }

    boolean onScheduledJobStopped(JobParameters parameters) {
        if (parameters == null) return true;
        boolean removed;
        JobService stoppedService;
        boolean scanning;
        boolean receiptSaved;
        synchronized (scanLock) {
            // Keep the stop decision, token removal, and receipt publication in one order.
            // A receipt that already won is complete work and must not trigger a redundant retry.
            removed = scheduledJobs.onJobStop(parameters);
            synchronized (activeJobServices) { stoppedService = activeJobServices.remove(parameters); }
            if (!removed && stoppedService == null) return false;
            scanning = scanRunning;
            receiptSaved = scanReceiptSavedJobs.remove(parameters);
            if (!receiptSaved && scanRunning && currentScanSequence != 0L && !scanIndependentTrigger
                    && !independentScanRequested && !scheduledJobs.hasActiveJobs())
                cancelJobScanRequested = true;
        }
        if (receiptSaved) lifecycle.onJobFinished(System.currentTimeMillis(), false);
        else lifecycle.onJobStopped(System.currentTimeMillis());
        persistLifecycleState();
        XposedBridge.log(receiptSaved
                ? "RecorderAutoTranscribe: system job stopped after saved scan receipt"
                : "RecorderAutoTranscribe: system job stopped; requesting retry");
        if (!scanning && removed && !receiptSaved)
            worker.post(() -> publishHealth("系统中断了后台任务，已请求系统重试"));
        return !receiptSaved;
    }

