    private static final class DoneSnapshot {
        final String path;
        final long size, modified, verifiedAt;
        final Bundle row;
        DoneSnapshot(String path, long size, long modified, long verifiedAt, Bundle row) {
            this.path = path; this.size = size; this.modified = modified;
            this.verifiedAt = verifiedAt; this.row = new Bundle(row);
        }
        boolean matches(String path, String name, long duration, long date, long size,
                        long modified, long now) {
            return this.path.equals(path) && this.size == size && this.modified == modified
                    && Objects.equals(row.getString("name"), name)
                    && row.getLong("duration") == duration && row.getLong("date") == date
                    && now - verifiedAt < DONE_RECHECK_MILLIS;
        }
    }

