    private static Class<?> boxPrimitive(Class<?> type) {
        if (!type.isPrimitive()) return type;
        if (type == int.class) return Integer.class;
        if (type == long.class) return Long.class;
        if (type == boolean.class) return Boolean.class;
        if (type == byte.class) return Byte.class;
        if (type == short.class) return Short.class;
        if (type == char.class) return Character.class;
        if (type == float.class) return Float.class;
        if (type == double.class) return Double.class;
        return type;
    }
    private static boolean matchParameters(Class<?>[] types, Object[] args) {
        int argCount = args == null ? 0 : args.length;
        if (types.length != argCount) return false;
        for (int i = 0; i < types.length; i++) {
            Class<?> pType = types[i];
            Object arg = args != null ? args[i] : null;
            if (arg == null) {
                if (pType.isPrimitive()) return false;
            } else {
                Class<?> boxed = boxPrimitive(pType);
                if (!boxed.isInstance(arg)) return false;
            }
        }
        return true;
    }
    private Object invoke(Object target, String name, Object... args) throws Exception {
        if (target == null) throw new NullPointerException("invoke target is null: " + name);
        Class<?> c = target instanceof Class ? (Class<?>) target : target.getClass();
        for (Class<?> curr = c; curr != null; curr = curr.getSuperclass()) {
            for (Method m : curr.getDeclaredMethods()) {
                if (!m.getName().equals(name) || !matchParameters(m.getParameterTypes(), args)) continue;
                m.setAccessible(true);
                try { return m.invoke(target instanceof Class ? null : target, args); }
                catch (InvocationTargetException e) {
                    Throwable cause = e.getCause();
                    throw cause instanceof Exception ? (Exception) cause : new Exception(cause);
                }
            }
        }
        for (Method m : c.getMethods()) {
            if (!m.getName().equals(name) || !matchParameters(m.getParameterTypes(), args)) continue;
            m.setAccessible(true);
            try { return m.invoke(target instanceof Class ? null : target, args); }
            catch (InvocationTargetException e) {
                Throwable cause = e.getCause();
                throw cause instanceof Exception ? (Exception) cause : new Exception(cause);
            }
        }
        throw new NoSuchMethodException(c.getName() + "." + name);
    }
    private Object stat(String c, String m, Object... a) throws Exception { return invoke(cls(c), m, a); }
